# ---------------------------------------------------------------------------
# Scaffold Synthesizer Engine
# ---------------------------------------------------------------------------
class MTVScaffoldSynthesizer:
    """
    Core scaffolding synthesizer responsible for executing the atomic 3-step
    instantiation of Model, Template, and View.
    """
    def __init__(self, target_project_directory_path: Path):
        self.target_project_directory_path = target_project_directory_path.resolve()
        self.storage_directory_path = self.target_project_directory_path / "storage"
        self.mfdb_directory_path = self.storage_directory_path / "mfdb"
        self.data_directory_path = self.mfdb_directory_path / "data"
        self.templates_directory_path = self.target_project_directory_path / "templates"
        self.static_directory_path = self.target_project_directory_path / "static"

    def instantiate_archetype_scaffold(
        self,
        archetype_identifier_key: str,
        custom_project_display_title: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Instantiates a complete MTV project unit for a selected archetype:
        1. Materializes the Model (105a.mfdb.bejson + data/*.105.bejson with UUIDv4).
        2. Materializes the Template (Copies zero-filler BEHTML scaffolds into templates/).
        3. Materializes the View (Emits build_site.py with strategy renderers).
        """
        archetype_definition = mtv_core.bejson_cms_get_archetype(archetype_identifier_key)
        project_title = (custom_project_display_title or archetype_definition["archetype_name"]).strip()

        logger.info("Scaffolding MTV unit: '%s' into %s", project_title, self.target_project_directory_path)

        # Ensure directory skeleton
        self.data_directory_path.mkdir(parents=True, exist_ok=True)
        self.templates_directory_path.mkdir(parents=True, exist_ok=True)
        (self.static_directory_path / "css").mkdir(parents=True, exist_ok=True)

        # -------------------------------------------------------------------
        # Step 1: Materialize Model ($M$)
        # -------------------------------------------------------------------
        manifest_file_path = self._materialize_105_mfdb_model(archetype_definition, project_title)

        # -------------------------------------------------------------------
        # Step 2: Materialize Template ($T$)
        # -------------------------------------------------------------------
        copied_templates_list = self._materialize_behtml_templates(archetype_definition)

        # -------------------------------------------------------------------
        # Step 3: Materialize View ($V$)
        # -------------------------------------------------------------------
        emitted_build_script_path = self._materialize_view_pipeline(archetype_definition, project_title)

        # -------------------------------------------------------------------
        # Step 4: Run Fluff Linter Verification Gate
        # -------------------------------------------------------------------
        linter_status = self._verify_zero_fluff_gate()

        summary_report: Dict[str, Any] = {
            "status": "success" if linter_status else "warning_fluff_detected",
            "project_directory": str(self.target_project_directory_path),
            "manifest_path": str(manifest_file_path),
            "archetype_id": archetype_definition["archetype_id"],
            "archetype_name": archetype_definition["archetype_name"],
            "entities_created": [entity["entity_name"] for entity in archetype_definition["entities"]],
            "templates_installed": copied_templates_list,
            "build_script_path": str(emitted_build_script_path),
            "zero_fluff_verified": linter_status
        }
        return summary_report

    def _materialize_105_mfdb_model(
        self,
        archetype_definition: Dict[str, Any],
        project_title: str
    ) -> Path:
        """Constructs an MFDB v1.40 database with Format 105 entities."""
        entities_input_list: List[Dict[str, Any]] = []

        for entity_metadata in archetype_definition["entities"]:
            entity_name = entity_metadata["entity_name"]
            table_filename = f"{entity_name.lower()}.105.bejson"
            relative_file_path = f"data/{table_filename}"

            # Construct verified 105 field descriptors with field_uuid
            field_descriptors_list: List[Dict[str, Any]] = []
            for field_spec in entity_metadata["fields"]:
                field_descriptor = mtv_core.bejson_105_construct_field_descriptor(
                    field_name_identifier=field_spec["name"],
                    field_primitive_type=field_spec["type"],
                    foreign_key_target_entity=field_spec.get("fk_target_entity"),
                    foreign_key_on_delete_behavior=field_spec.get("fk_on_delete"),
                    field_description_text=field_spec.get("description", "")
                )
                field_descriptors_list.append(field_descriptor)

            entities_input_list.append({
                "name": entity_name,
                "description": entity_metadata["table_description"],
                "primary_key": entity_metadata["primary_key_column_name"],
                "fields": field_descriptors_list,
                "format_version": "105",
                "file_path": relative_file_path
            })

        # Create MFDB manifest at mfdb_directory_path
        manifest_file_string = mfdb_core_create_database(
            root_dir=str(self.mfdb_directory_path),
            db_name=archetype_definition["archetype_id"],
            entities=entities_input_list,
            db_description=f"Backing MFDB v1.40 database for {project_title}.",
            schema_version="1.4.0",
            mfdb_version="1.40",
            network_role="Master"
        )
        manifest_file_path = Path(manifest_file_string)
        manifest_105a_path = self.mfdb_directory_path / "105a.mfdb.bejson"
        if manifest_file_path.name == "104a.mfdb.bejson" and not manifest_105a_path.exists():
            shutil.copy2(manifest_file_string, manifest_105a_path)

        # Enable active referential integrity enforcement
        mfdb_core_enable_ref_integrity(str(manifest_file_path))
        if manifest_105a_path.exists():
            try:
                mfdb_core_enable_ref_integrity(str(manifest_105a_path))
            except Exception:
                pass

        # Seed structural initial row in Category entity
        category_entity_name = "Category"
        if any(e["name"] == category_entity_name for e in entities_input_list):
            category_doc = mfdb_core_get_entity_doc(str(manifest_file_path), category_entity_name)
            cat_fmap = mtv_core.bejson_105_get_field_map(category_doc)
            cat_fields = category_doc.get("Fields", [])
            initial_category_row = [None] * len(cat_fields)
            
            initial_cat_uuid = mtv_core.bejson_105_mint_uuid()
            if "cat_uuid" in cat_fmap:
                initial_category_row[cat_fmap["cat_uuid"]] = initial_cat_uuid
            if "cat_name" in cat_fmap:
                initial_category_row[cat_fmap["cat_name"]] = "General"
            if "cat_slug" in cat_fmap:
                initial_category_row[cat_fmap["cat_slug"]] = "general"
            if "cat_order_index" in cat_fmap:
                initial_category_row[cat_fmap["cat_order_index"]] = 1

            mfdb_core_add_entity_record_105(
                manifest_path=str(manifest_file_path),
                entity_name=category_entity_name,
                values=initial_category_row
            )

        logger.info("Materialized Model: %s with %d entities", manifest_file_path, len(entities_input_list))
        return manifest_file_path

    def _materialize_behtml_templates(self, archetype_definition: Dict[str, Any]) -> List[str]:
        """Copies required zero-filler BEHTML 8-lane templates and core css into templates/."""
        installed_templates: List[str] = []
        bound_templates = list(archetype_definition.get("bound_templates", []))
        # Always install master index template
        if "scaffold_master_index.html" not in bound_templates:
            bound_templates.append("scaffold_master_index.html")

        # Copy framework css
        css_source_path = Path(TEMPLATES_SOURCE_DIRECTORY) / "framework_core_layout.css"
        if css_source_path.exists():
            shutil.copy2(css_source_path, self.templates_directory_path / "framework_core_layout.css")
            shutil.copy2(css_source_path, self.static_directory_path / "css" / "framework_core_layout.css")

        for template_name in bound_templates:
            template_source_file = Path(TEMPLATES_SOURCE_DIRECTORY) / template_name
            target_template_file = self.templates_directory_path / template_name
            if template_source_file.exists():
                shutil.copy2(template_source_file, target_template_file)
                installed_templates.append(template_name)
            else:
                logger.warning("Template source not found: %s", template_source_file)

        logger.info("Materialized Template: Installed %d templates into %s", len(installed_templates), self.templates_directory_path)
        return installed_templates

    def _materialize_view_pipeline(self, archetype_definition: Dict[str, Any], project_title: str) -> Path:
        """Emits standalone zero-dependency build_site.py equipped with polymorphic renderers."""
        build_site_script_path = self.target_project_directory_path / "build_site.py"
        with open(build_site_script_path, "w", encoding="utf-8") as script_handle:
            script_handle.write(STANDALONE_BUILD_SITE_SCRIPT_HEADER)
        
        # Grant executable permissions
        os.chmod(build_site_script_path, 0o755)
        logger.info("Materialized View: Emitted standalone build script %s", build_site_script_path)
        return build_site_script_path

    def _verify_zero_fluff_gate(self) -> bool:
        """Runs the scaffold fluff linter across all generated files."""
        try:
            from scaffold_fluff_linter import audit_template
        except ImportError:
            import importlib.util
            linter_path = os.path.join(CURRENT_MODULE_DIRECTORY, "scaffold_fluff_linter.py")
            spec = importlib.util.spec_from_file_location("scaffold_fluff_linter", linter_path)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            audit_template = mod.audit_template
        violations_count = 0
        for root_dir, _, file_names in os.walk(str(self.target_project_directory_path)):
            for filename in file_names:
                file_path = Path(root_dir) / filename
                if file_path.suffix.lower() in (".html", ".htm", ".json", ".bejson"):
                    findings = audit_template(file_path)
                    if findings:
                        violations_count += len(findings)
                        for finding in findings:
                            logger.warning("Fluff violation in %s: %s", file_path.name, finding)

        if violations_count > 0:
            logger.warning("Zero Fluff Gate: %d violations flagged.", violations_count)
            return False
        logger.info("Zero Fluff Gate: PASS (Zero filler detected).")
        return True
