def bejson_load_file(target_file_path: Path) -> Dict[str, Any]:
    with open(target_file_path, "r", encoding="utf-8") as file_handle:
        return json.load(file_handle)

def bejson_get_field_map(bejson_document_data: Dict[str, Any]) -> Dict[str, int]:
    return {field["name"]: column_index for column_index, field in enumerate(bejson_document_data.get("Fields", []))}

